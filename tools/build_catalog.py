def img(ascii_name):
    """Фото заказчика из assets/img или наше фото с тем же именем."""
    cyr = set("абвгдеёжзийклмнопрстуфхцчшщъыьэюя")
    if ascii_name.startswith("assets/img/"):
        return ascii_name
    if re.search(r"\.(jpe?g|png|webp)$", ascii_name, re.I):
        return "assets/img/" + ascii_name
    key = ascii_name if (set(ascii_name.lower()) & cyr) else ascii_name.lower().replace(" ", "-")
    file = ASCII.get(key, key) + ".jpg"
    return "assets/img/" + file


def pack_piece(weight, price):
    """Фасовка с ценой за упаковку (прайс документа 1): price — уже за этот вес."""
    return {"weight": weight, "price": int(price), "total": int(price)}


def pack(weight, price):
    """Фасовка. Для весовых (1 кг, 2 кг, 3 кг ...) у прайса цена за кг,
    поэтому total = weight * price; для фиксированной (200 г) price — за упаковку."""
    w = weight.lower().replace(",", ".")
    if w == "вес":
        # В прайсе «вес» — рыба на развес: цена указана за килограмм
        return {"weight": "1 кг", "price": int(price), "total": int(price)}
    m = re.fullmatch(r"([\d.]+)\s*кг", w)
    g = re.fullmatch(r"(\d+)\s*г", w)
    if re.fullmatch(r"\d+\s*шт", w):
        return {"weight": weight, "price": int(price), "total": int(price)}
    if m:
        kilos = float(m.group(1))
        return {"weight": weight, "price": int(price), "total": round(kilos * price)}
    if g:
        grams = int(g.group(1))
        return {"weight": weight, "price": int(round(price * 1000 / grams)), "total": int(price)}
    raise ValueError("Неизвестный вес: " + weight)


def item(id, name, packs, img_name, desc, tags, badge=None, old_discount=None, choose=None, per="", piece=False):
    """packs — [(вес, цена за кг / за упаковку / за штуку)], первый вариант — в витрине.
    choose — фасовка витрины по весу. old_discount — завышенная «старая цена» для
    витрины; в прайсе поставщика она отсутствует, менеджер подтверждает цены.
    per="шт" — позиция продаётся штуками (яйца, стекло, порционная упаковка)."""
    built = [(pack_piece if piece else pack)(w, p) for w, p in packs]
    chosen_idx = 0
    if choose:
        chosen_idx = next(i for i, p in enumerate(built) if p["weight"] == choose)
    chosen = built[chosen_idx]
    unit = per or "кг"
    old_price = None
    if old_discount:
        base = chosen["price"] / (1 - old_discount / 100)
        old_price = int(round(base / 10) * 10)
    return {
        "id": id,
        "name": name,
        "weight": chosen["weight"],
        "price": chosen["price"],
        "oldPrice": old_price,
        "unit": unit,
        "piece": bool(piece),
        "packPrice": chosen["total"],
        "img": img(img_name),
        "badge": badge,
        "desc": desc,
        "tags": tags,
        "packs": built,
    }


